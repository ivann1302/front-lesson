/* global fetch, process, URL */

import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

const sitemapUrl = "https://www.hackfrontend.com/sitemap.xml";
const outputFilename = resolve("src/sources/hackfrontend.generated.ts");

function decodeXml(value) {
  return value
    .replaceAll("&amp;", "&")
    .replaceAll("&lt;", "<")
    .replaceAll("&gt;", ">")
    .replaceAll("&quot;", '"')
    .replaceAll("&#39;", "'");
}

function sourceFromUrl(value) {
  const url = new URL(value);
  if (url.origin !== "https://www.hackfrontend.com") return undefined;
  const segments = url.pathname.split("/").filter(Boolean);
  if (segments[0] !== "ru" || segments[1] !== "docs" || !segments[2]) return undefined;
  const section = segments[2];
  const slug = segments.slice(3).join("/");
  const normalizedSlug = slug
    .toLocaleLowerCase("en-US")
    .replace(/[^a-z0-9/-]+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "");
  return {
    id: `hackfrontend:${section}${normalizedSlug ? `/${normalizedSlug}` : ""}`,
    section,
    slug,
    url: url.href,
  };
}

const response = await fetch(sitemapUrl, {
  headers: {
    accept: "application/xml,text/xml;q=0.9,*/*;q=0.1",
    "user-agent": "FrontendMentorKnowledgeIndex/1.0 (+reference-only; sitemap metadata)",
  },
});
if (!response.ok) throw new Error(`Hack Frontend sitemap returned ${response.status}`);
const xml = await response.text();
const sources = [
  ...new Set([...xml.matchAll(/<loc>([^<]+)<\/loc>/g)].map((match) => decodeXml(match[1]))),
]
  .map(sourceFromUrl)
  .filter((source) => source !== undefined)
  .sort((left, right) => left.url.localeCompare(right.url));
if (!sources.length) throw new Error("Hack Frontend sitemap contains no Russian docs URLs");

const generated = `// Generated by pnpm content:sources:sync. Do not edit manually.\n\n// prettier-ignore\nexport const hackFrontendSourceSnapshot = ${JSON.stringify(
  {
    provider: "Hack Frontend",
    homepage: "https://www.hackfrontend.com/ru/docs/introduction",
    sitemap: sitemapUrl,
    syncedAt: new Date().toISOString().slice(0, 10),
    usage: "reference-only",
    items: sources,
  },
  null,
  2,
)} as const;\n`;

await mkdir(dirname(outputFilename), { recursive: true });
await writeFile(outputFilename, generated, "utf8");
process.stdout.write(`Hack Frontend source index synced: ${sources.length} docs URLs\n`);
